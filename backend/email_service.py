"""
Sentinel - Automated SMTP Email Dispatcher for Intrusion & Integrity Alerts
"""

import smtplib
import os
import asyncio
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from typing import List, Optional

SMTP_HOST = os.getenv("SMTP_HOST", "smtp.gmail.com")
SMTP_PORT = int(os.getenv("SMTP_PORT", 587))
SMTP_USER = os.getenv("SMTP_USER", "pravin11122243424@gmail.com")
SMTP_PASS = os.getenv("SMTP_PASS", "rkinadjzagebuvqd")
ALERT_RECIPIENT = os.getenv("ALERT_RECIPIENT", "pravint2006@gmail.com")

def send_alert_email_sync(
    target_name: str,
    target_url: str,
    severity: str,
    alert_title: str,
    message: str,
    evidence: Optional[List[str]] = None,
    recipient: Optional[str] = None
) -> bool:
    to_email = recipient or ALERT_RECIPIENT
    if not SMTP_USER or not SMTP_PASS or not to_email:
        print("[SMTP] Incomplete configuration, skipping email dispatch.")
        return False

    clean_pass = SMTP_PASS.replace(" ", "")

    msg = MIMEMultipart("alternative")
    sev_emoji = "🚨" if severity in ("CRITICAL", "HIGH") else "⚠️"
    msg["Subject"] = f"{sev_emoji} [{severity}] Sentinel Alert: {target_name}"
    msg["From"] = f"Sentinel Security Monitor <{SMTP_USER}>"
    msg["To"] = to_email

    evidence_items = evidence or []
    evidence_html = "".join(f"<li style='margin-bottom: 4px; font-family: monospace; font-size: 13px;'>{e}</li>" for e in evidence_items)
    evidence_text = "\n".join(f"- {e}" for e in evidence_items)

    text_content = f"""[SENTINEL INTRUSION & INTEGRITY ALERT]
Severity: {severity}
Target: {target_name} ({target_url})
Incident: {alert_title}

Details:
{message}

Forensics / Evidence:
{evidence_text}

Dashboard: http://52.207.250.243/
"""

    badge_bg = "#dc2626" if severity in ("CRITICAL", "HIGH") else "#d97706"

    html_content = f"""<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
</head>
<body style="margin: 0; padding: 24px; background-color: #f8fafc; font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; color: #1e293b;">
  <div style="max-width: 600px; margin: 0 auto; background: #ffffff; border: 1px solid #e2e8f0; border-radius: 10px; overflow: hidden; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.05);">
    
    <!-- Header -->
    <div style="background: #0f172a; padding: 20px 24px; display: flex; align-items: center;">
      <h2 style="margin: 0; color: #ffffff; font-size: 18px; letter-spacing: -0.02em;">🛡️ Sentinel Security Monitor</h2>
    </div>

    <!-- Alert Banner -->
    <div style="padding: 16px 24px; background: {badge_bg}15; border-bottom: 1px solid {badge_bg}30;">
      <span style="background: {badge_bg}; color: #ffffff; font-size: 11px; font-weight: 700; padding: 3px 8px; border-radius: 4px; letter-spacing: 0.05em; text-transform: uppercase;">
        {severity} INCIDENT
      </span>
      <h3 style="margin: 10px 0 4px; color: #0f172a; font-size: 17px;">{alert_title}</h3>
      <p style="margin: 0; font-size: 13px; color: #64748b;">Target: <strong>{target_name}</strong> (<code>{target_url}</code>)</p>
    </div>

    <!-- Content Body -->
    <div style="padding: 24px;">
      <h4 style="margin: 0 0 8px; font-size: 14px; text-transform: uppercase; letter-spacing: 0.04em; color: #475569;">Description</h4>
      <p style="margin: 0 0 20px; font-size: 14px; line-height: 1.6; color: #334155; background: #f1f5f9; padding: 12px 16px; border-radius: 6px;">
        {message}
      </p>

      {f'''
      <h4 style="margin: 0 0 8px; font-size: 14px; text-transform: uppercase; letter-spacing: 0.04em; color: #475569;">Forensic Evidence</h4>
      <ul style="margin: 0 0 24px; padding-left: 20px; color: #334155;">
        {evidence_html}
      </ul>
      ''' if evidence_items else ''}

      <div style="text-align: center; margin-top: 24px; padding-top: 20px; border-top: 1px solid #e2e8f0;">
        <a href="http://52.207.250.243/" style="background: #2563eb; color: #ffffff; text-decoration: none; padding: 10px 22px; font-size: 14px; font-weight: 600; border-radius: 6px; display: inline-block;">
          Open Live Sentinel Dashboard →
        </a>
      </div>
    </div>

    <!-- Footer -->
    <div style="background: #f8fafc; padding: 14px 24px; font-size: 12px; color: #94a3b8; text-align: center; border-top: 1px solid #e2e8f0;">
      Automated alert generated by Sentinel Continuous Integrity Engine on AWS EC2.
    </div>
  </div>
</body>
</html>
"""

    msg.attach(MIMEText(text_content, "plain"))
    msg.attach(MIMEText(html_content, "html"))

    try:
        with smtplib.SMTP(SMTP_HOST, SMTP_PORT, timeout=15) as server:
            server.ehlo()
            server.starttls()
            server.ehlo()
            server.login(SMTP_USER, clean_pass)
            server.send_message(msg)
            print(f"[SMTP] Successfully delivered alert email to {to_email}")
            return True
    except Exception as e:
        print(f"[SMTP Error] Failed to send email via {SMTP_HOST}:{SMTP_PORT} -> {e}")
        return False

async def send_alert_email_async(*args, **kwargs) -> bool:
    """Dispatches email asynchronously without blocking the main event loop."""
    return await asyncio.to_thread(send_alert_email_sync, *args, **kwargs)
